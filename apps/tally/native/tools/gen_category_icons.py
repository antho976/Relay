#!/usr/bin/env python3
"""Writes src/category_icons.rs: every category icon key the Kotlin app knows (ui/common/Icons.kt,
Material Rounded) as the icon's SVG path data on its 24-unit grid, filled.

The SVGs come from Google's @material-design-icons/svg npm package (Apache 2.0), extracted to a
folder given as the first argument:
  curl -sL https://registry.npmjs.org/@material-design-icons/svg/-/svg-0.14.13.tgz | tar xz -C /tmp
  python3 tools/gen_category_icons.py /tmp/package/round"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
svgs = pathlib.Path(sys.argv[1])
# The Kotlin app left the repo after c8aa08f (antho976/Tally's cf4b63b, before Tally moved into
# apps/tally); its sources are read from that commit, relative to apps/tally ("./").
KOTLIN_REV = "c8aa08f1f67b366c7c15a8b52252abb0353317a6"
def kotlin(path):
    import subprocess
    return subprocess.run(["git", "-C", str(root), "show", f"{KOTLIN_REV}:./{path}"], check=True, capture_output=True, text=True).stdout
src = kotlin("app/src/main/java/com/tally/app/ui/common/Icons.kt")
pairs = re.findall(r'"([a-z0-9_-]+)" to Icons\.(?:AutoMirrored\.)?Rounded\.([A-Za-z0-9]+)', src)
def snake(name):
    s = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', name)
    s = re.sub(r'(?<=[A-Za-z])([0-9])', r'_\1', s) if not (svgs / (s.lower() + ".svg")).exists() else s
    return s.lower()
out, missing = [], []
seen = set()
for key, compose in pairs:
    if key in seen:
        continue
    seen.add(key)
    f = None
    for cand in [snake(compose), re.sub(r'(?<=[a-z])([A-Z])', r'_\1', compose).lower()]:
        if (svgs / f"{cand}.svg").exists():
            f = svgs / f"{cand}.svg"
            break
    if f is None:
        missing.append((key, compose))
        continue
    svg = f.read_text()
    ds = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    for c in re.findall(r'<circle([^>]*)/?>', svg):
        a = dict(re.findall(r'(cx|cy|r)="([-\d.]+)"', c))
        cx, cy, r = float(a.get("cx", 0)), float(a.get("cy", 0)), float(a["r"])
        ds.append(f"M{cx - r:g} {cy:g}a{r:g} {r:g} 0 1 0 {2 * r:g} 0a{r:g} {r:g} 0 1 0 {-2 * r:g} 0z")
    if re.search(r'<(rect|ellipse|polygon)', svg):
        missing.append((key, compose + " (has shapes)"))
    out.append((key, " ".join(ds)))
lines = ["//! Generated by tools/gen_category_icons.py: the category icons, as the Kotlin app draws them",
         "//! (Material Rounded, from Google's material-design-icons, Apache 2.0), as SVG path data on",
         "//! the 24-unit grid, filled. Regenerate, don't edit.", "",
         "pub fn path(key: &str) -> Option<&'static str> {", "    Some(match key {"]
for key, d in out:
    lines.append(f'        "{key}" => "{d}",')
lines += ["        _ => return None,", "    })", "}", ""]
(root / "native/crates/tally-rs/src/category_icons.rs").write_text("\n".join(lines))
print(len(out), "icons;", "missing:", missing)
