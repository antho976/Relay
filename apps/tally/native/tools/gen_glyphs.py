#!/usr/bin/env python3
"""Writes src/glyphs.rs from the Kotlin app's glyph tables (Relay's set plus Tally's money set),
so both apps draw the same icons. Run from native/: python3 tools/gen_glyphs.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
# The Kotlin app left the repo after cf4b63b; its sources are read from that commit.
KOTLIN_REV = "cf4b63b52b9f742095cb05d884fe2e4d1510b7c6"
def kotlin(path):
    import subprocess
    return subprocess.run(["git", "-C", str(root), "show", f"{KOTLIN_REV}:{path}"], check=True, capture_output=True, text=True).stdout
kit = "app/src/main/java/com/tally/app/ui/kit"
shape = re.compile(r'GlyphShape\("([^"]*)",\s*(true|false),\s*(true|false),\s*(-?[\d.]+)f\)')
out = {}
src = kotlin(f"{kit}/Glyphs.kt")
for m in re.finditer(r'put\("([a-z0-9-]+)",\s*Glyph\(([\d.]+)f,\s*listOf\((.*?)\)\)\)', src, re.S):
    out[m[1]] = (float(m[2]), [(d, f == "true", s == "true", float(r)) for d, f, s, r in shape.findall(m[3])])
icon = kotlin(f"{kit}/Icon.kt")
money = icon[icon.index("private val MONEY"):]
for m in re.finditer(r'"([a-z0-9-]+)" to (stroked\((.*?)\)|Glyph\(([\d.]+)f,\s*listOf\((.*?)\)\)),?\n', money, re.S):
    if m[3] is not None:
        out[m[1]] = (1.0, [(d, False, True, 0.0) for d in re.findall(r'"([^"]*)"', m[3])])
    else:
        out[m[1]] = (float(m[4]), [(d, f == "true", s == "true", float(r)) for d, f, s, r in shape.findall(m[5])])
lines = ["//! Generated by tools/gen_glyphs.py from the Kotlin app's Glyphs.kt and Icon.kt: Relay's glyphs and",
         "//! Tally's money set, on the 16-unit grid, stroked unless marked filled. Regenerate, don't edit.", "",
         "pub struct Shape { pub d: &'static str, pub fill: bool, pub stroke: bool, pub rotate: f32 }", "",
         "pub struct Glyph { pub scale: f32, pub shapes: &'static [Shape] }", "",
         "pub fn get(name: &str) -> &'static Glyph {", "    match name {"]
for name in sorted(out):
    scale, shapes = out[name]
    parts = ", ".join(f'Shape {{ d: "{d}", fill: {str(f).lower()}, stroke: {str(s).lower()}, rotate: {r:.1f} }}' for d, f, s, r in shapes)
    lines.append(f'        "{name}" => &Glyph {{ scale: {scale:.4f}, shapes: &[{parts}] }},')
lines += ['        _ => get("fallback"),', "    }", "}", "",
          f"pub const NAMES: [&str; {len(out)}] = [{', '.join(repr(n).replace(chr(39), chr(34)) for n in sorted(out))}];", ""]
(root / "native/crates/tally-rs/src/glyphs.rs").write_text("\n".join(lines))
print(len(out), "glyphs")
